        ; [1, 5, 9, 13] <- [5, 9, 13, 1]
        movff   pkg_buffer+0x01,  temp_buffer_dec+0x05   ; 1 moves to 5
        movff   pkg_buffer+0x05,  temp_buffer_dec+0x09   ; 5 moves to 9
