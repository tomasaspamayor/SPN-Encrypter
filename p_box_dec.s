Multiply_By_9:
    ; W register currently holds the byte we want to multiply

    ; 1. Set the Upper and High bytes of the Table Pointer
    movlw   UPPER(Mult9_Table)
    movwf   TBLPTRU, A
    movlw   HIGH(Mult9_Table)
    movwf   TBLPTRH, A

    ; 2. Drop our data byte directly into the Low byte of the Table Pointer
    movwf   TBLPTRL, A      ; W still contains our data byte!

    ; 3. Read the flash memory
    tblrd* ; Reads the byte at TBLPTR into TABLAT

    ; 4. Move the result out
    movf    TABLAT, W, A    ; W now holds the result of byte * 9!
    return

