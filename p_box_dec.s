        ; --- Row 0: No Shift ---
        ; [0, 4, 8, 12] <- [0, 4, 8, 12]
        movff   pkg_buffer+0x00,  temp_buffer_dec+0x00
        movff   pkg_buffer+0x04,  temp_buffer_dec+0x04
        movff   pkg_buffer+0x08,  temp_buffer_dec+0x08
        movff   pkg_buffer+0x0C, temp_buffer_dec+0x0C
	
